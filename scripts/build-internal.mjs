// The internal build: everything, including every non-public theme, into
// dist-internal/. Never published.
//
// src/internal.ts is generated here (git-ignored): the public entry plus, for
// each internal theme, every *Adapter.ts it contains, plus the files listed in
// package.json's "atdoc.internalFiles" (pipeline, mermaid, ...). A new theme
// folder needs no edit — provided its adapter file is named *Adapter.ts.

import { writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { execSync } from 'node:child_process';
import { discoverThemes, readAtdocConfig, root, srcDir } from './themes.mjs';

const t = discoverThemes();
const { internalFiles } = readAtdocConfig();

const lines = [
  '// GENERATED by scripts/build-internal.mjs — do not edit. Never published.',
  "export * from './index.js';",
];
for (const theme of t.internalThemes) {
  for (const f of t.adapterFiles(theme)) lines.push(`export * from './${theme}/${f.replace(/\.ts$/, '.js')}';`);
}
for (const f of internalFiles) {
  const rel = f.replace(/^src\//, '');
  if (rel === 'internal.ts' || !existsSync(join(srcDir, rel))) continue;
  lines.push(`export * from './${rel.replace(/\.ts$/, '.js')}';`);
}
writeFileSync(join(srcDir, 'internal.ts'), lines.join('\n') + '\n');

writeFileSync(
  join(root, 'tsconfig.internal.json'),
  JSON.stringify({ extends: './tsconfig.json', compilerOptions: { outDir: 'dist-internal' }, include: ['src'], exclude: [] }, null, 2) + '\n',
);

const run = (cmd) => execSync(cmd, { cwd: root, stdio: 'inherit' });
run('node scripts/build-css.mjs');
run('npx tsc -p tsconfig.internal.json');
